"""Write outputs/numbers.json: the single source of every number quoted anywhere (ADR 0006).

Overall totals are computed here straight from the tables (not by summing the daily CSV),
so tests/check_numbers.py can compare the two independent computations.
"""
import csv
import json
from pathlib import Path

from run_sql import connect

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"


def read_csv(name):
    with open(OUT / f"{name}.csv") as f:
        return list(csv.DictReader(f))


def one_row(con, sql):
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    return dict(zip(cols, cur.fetchall()[0]))


def kpi_overall(con):
    row = one_row(con, """
        SELECT (SELECT count(*) FROM bids)                                   AS bids,
               (SELECT count(*) FROM bids SEMI JOIN impressions USING (bid_id)) AS bids_won,
               count(*)                                                       AS impressions,
               sum(pay_price) / 100000.0                                      AS spend_cny,
               sum(clicks)                                                    AS clicks,
               sum(conversion)                                                AS conversions,
               count(DISTINCT advertiser_id)                                  AS advertisers,
               min(ts)::DATE::VARCHAR AS first_day, max(ts)::DATE::VARCHAR    AS last_day
        FROM impressions""")
    row["win_rate"] = row["bids_won"] / row["bids"]
    row["cpm_cny"] = row["spend_cny"] * 1000 / row["impressions"]
    row["ctr"] = row["clicks"] / row["impressions"]
    row["cpc_cny"] = row["spend_cny"] / row["clicks"]
    return row


def main():
    con = connect()
    numbers = {
        "_note": "Generated by analysis/export_numbers.py. Do not edit by hand.",
        "units": {"money": "CNY (2013), iPinYou; Criteo cost is a transformed unit",
                  "cpm": "CNY per 1,000 impressions"},
        "ipinyou_kpi": kpi_overall(con),
        "ipinyou_advertisers": read_csv("kpi_advertiser"),
        "auction": {r["exchange"]: r for r in read_csv("auction_health") if r["slot_visibility"] == "ALL"},
        "floor_sizing_all": [r for r in read_csv("floor_sizing") if r["exchange"] == "ALL"],
        "criteo_overall": one_row(con, """
            SELECT count(*) AS impressions, count(DISTINCT campaign) AS campaigns, sum(cost) AS spend,
                   sum(click) AS clicks, sum(attribution) AS conversions FROM attribution"""),
        "criteo_concentration": one_row(con, """
            SELECT max(cumulative_spend_share) FILTER (WHERE spend_rank <= 135) AS top20pct_spend_share,
                   max(cumulative_spend_share) FILTER (WHERE spend_rank <= 68)  AS top10pct_spend_share
            FROM read_csv('outputs/campaign_segments.csv')"""),
        "segments": {r["segment"]: r for r in read_csv("segment_summary")},
    }
    ab = OUT / "ab_readout.json"
    if ab.exists():
        numbers["ab"] = json.loads(ab.read_text())
    (OUT / "numbers.json").write_text(json.dumps(numbers, indent=2, default=str))
    print(f"wrote outputs/numbers.json ({len(numbers)} sections)")


if __name__ == "__main__":
    main()
