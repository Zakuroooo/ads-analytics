"""Write HANDOVER.md (git-ignored): the 4 resume bullets + links, with every number traced to its
numbers.json key and the raw value, so the Resume chat can check each claim.
Run: python analysis/write_handover.py
"""
import json
from pathlib import Path

from render_docs import half_up

ROOT = Path(__file__).resolve().parent.parent
n = json.loads((ROOT / "outputs" / "numbers.json").read_text())
k, seg, ab = n["ipinyou_kpi"], n["segments"], n["ab"]
x30 = next(r for r in n["floor_sizing_all"] if r["min_floor_fen_cpm"] == "30")


def pct(v, d=0):
    return f"{half_up(float(v) * 100, d)}%"


bids_m = f"{half_up(k['bids'] / 1e6, 1)}M"
imps_m = f"{half_up(k['impressions'] / 1e6, 1)}M"
users_m = f"{half_up((ab['counts']['T']['users'] + ab['counts']['C']['users']) / 1e6, 2)}M"
ratio = f"{half_up(float(seg['FIX']['cpa']) / float(seg['PROTECT']['cpa']), 1)}×"
conv = ab["primary_conversion"]

bullets = [
    f"Engineered a **DuckDB SQL** KPI layer over **{bids_m} bids** and {imps_m} impressions, reconciled by **29 tie-out checks**",
    f"Built an **Excel/Sheets** floor-price model: floors bound **{pct(n['auction']['ALL']['floor_binding_rate'])}** of floored auctions; "
    f"break-even at **{pct(x30['breakeven_retention'])} retention**",
    f"Segmented **{n['criteo_overall']['campaigns']} ad campaigns** by spend and CPA, flagging a group with **{pct(seg['FIX']['spend_share'])} of spend** "
    f"paying **{ratio} more** per conversion",
    f"Read out a randomised **A/B test on {users_m} users**: **+{pct(conv['rel_lift'])} conversion lift** "
    f"(95% CI +{pct(conv['rel_ci95'][0])} to +{pct(conv['rel_ci95'][1])}), pre-registered",
]

trace = [
    ("11.5M bids", "ipinyou_kpi.bids", k["bids"]),
    ("4.7M impressions", "ipinyou_kpi.impressions", k["impressions"]),
    ("29 tie-out checks", "count of PASS lines from tests/check_numbers.py (not a numbers.json key)", "29/29 on last run"),
    ("floors bound 37%", "auction.ALL.floor_binding_rate", n["auction"]["ALL"]["floor_binding_rate"]),
    ("51% break-even", "floor_sizing_all[min_floor_fen_cpm=30].breakeven_retention", x30["breakeven_retention"]),
    ("675 campaigns", "criteo_overall.campaigns", n["criteo_overall"]["campaigns"]),
    ("44% of spend", "segments.FIX.spend_share", seg["FIX"]["spend_share"]),
    ("4.7× more per conversion", "segments.FIX.cpa / segments.PROTECT.cpa", f"{seg['FIX']['cpa']} / {seg['PROTECT']['cpa']}"),
    ("13.98M users", "ab.counts.T.users + ab.counts.C.users", ab["counts"]["T"]["users"] + ab["counts"]["C"]["users"]),
    ("+59% conversion lift", "ab.primary_conversion.rel_lift", conv["rel_lift"]),
    ("95% CI +54% to +65%", "ab.primary_conversion.rel_ci95", conv["rel_ci95"]),
]

lines = [
    "# HANDOVER: ads-analytics → Resume chat",
    "*Generated by `analysis/write_handover.py` from `outputs/numbers.json`. Git-ignored. Re-run after any rebuild.*",
    "",
    "**Framing:** Ads analytics for a delivery marketplace, built on public ad data (iPinYou RTB 2013, Criteo Attribution, "
    "Criteo Uplift). Never Swiggy data.",
    "",
    "**Links (both public):** GitHub https://github.com/Zakuroooo/ads-analytics · Live https://slotwise-ads.vercel.app",
    "**Portal:** Project · Company = Personal · Oct 2026 · Category: Data Analytics / Business Analytics.",
    "",
    "## 4 resume bullets (one line each, 1–3 bold phrases, no AI-tool names)",
    "",
]
for i, b in enumerate(bullets, 1):
    lines.append(f"{i}. {b}  ({len(b.replace('**', ''))} visible chars)")
lines += ["", "## Every number traced", "", "| Claim in bullet | numbers.json key | Raw value |", "|---|---|---|"]
lines += [f"| {c} | `{key}` | {v} |" for c, key, v in trace]
lines += [
    "",
    "## Definitions to say in the interview",
    "- **Floors bound 37%:** among impressions with a floor > 0, the share where the price paid was ≤ the floor (second-price auction: no rival bid above it).",
    "- **51% break-even:** at a 30-fen minimum floor, the share of at-risk impressions that must still sell for revenue to stay flat (ADR 0007).",
    "- **4.7×:** CPA of the FIX group (above-median spend, above-median CPA) divided by CPA of the PROTECT group.",
    "- **+59%:** intent-to-treat relative lift in conversion rate per user; decision rule written before the readout; independently re-derived.",
    "",
    "## Limits to keep in mind",
    "Fill rate and ROAS not computable (stand-ins: win rate, CPA). Prices are 2013 CNY; Criteo cost is transformed. "
    "The A/B data pools several tests, so a single-campaign holdout should confirm the lift. Effect-on-exposed estimate not used.",
]
(ROOT / "HANDOVER.md").write_text("\n".join(lines) + "\n")
print("wrote HANDOVER.md")
